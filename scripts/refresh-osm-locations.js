import { writeFile } from "node:fs/promises";

// Download once at maintenance time, rather than querying public Overpass
// servers for every customer. Both browser and server import this snapshot.
const query = `[out:json][timeout:180];
area["ISO3166-1"="LK"]["admin_level"="2"]->.country;
rel(area.country)["boundary"="administrative"]["admin_level"="5"];
foreach {
  out tags;
  map_to_area->.district;
  nwr(area.district)["place"~"^(city|town|village|suburb)$"];
  out tags;
}`;

const endpoints = process.env.OVERPASS_URL
  ? [process.env.OVERPASS_URL]
  : ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"];

let data;
for (const endpoint of endpoints) {
  try {
    console.log(`Downloading Sri Lanka locations from ${endpoint}`);
    const response = await fetch(`${endpoint}?${new URLSearchParams({ data: query })}`, {
      headers: { "User-Agent": "TeenGirlsLK-location-refresh/1.0", Accept: "application/json" },
      signal: AbortSignal.timeout(210000)
    });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    data = await response.json();
    if (data.remark || !Array.isArray(data.elements)) throw new Error(data.remark || "Invalid Overpass response");
    break;
  } catch (error) {
    data = undefined;
    console.warn(`Download failed: ${error.message}`);
  }
}
if (!data) throw new Error("Could not refresh OpenStreetMap locations; existing snapshot was preserved.");

const districts = new Map();
let cities;
for (const element of data.elements) {
  const tags = element.tags || {};
  const name = (tags["name:en"] || tags.name || "").trim();
  if (element.type === "relation" && tags.boundary === "administrative" && tags.admin_level === "5") {
    const district = name.replace(/\s+District$/i, "");
    if (!district) throw new Error("District without a name");
    cities = districts.get(district) || new Set();
    districts.set(district, cities);
  } else if (cities && /^(city|town|village|suburb)$/.test(tags.place) && name) {
    cities.add(name);
  }
}

if (districts.size !== 25 || [...districts.values()].some((items) => !items.size)) {
  throw new Error(`Incomplete OpenStreetMap result (${districts.size} districts); existing snapshot was preserved.`);
}
const locations = Object.fromEntries([...districts].sort(([a], [b]) => a.localeCompare(b, "en"))
  .map(([district, names]) => [district, [...names].sort((a, b) => a.localeCompare(b, "en"))]));
const timestamp = data.osm3s?.timestamp_osm_base || new Date().toISOString();
const source = `// Generated by npm run locations:refresh. Do not edit manually.
// OpenStreetMap contributors, ODbL 1.0: https://www.openstreetmap.org/copyright
// City options include mapped cities, towns, villages and suburbs in each district.
export const LOCATION_DATA_UPDATED_AT = ${JSON.stringify(timestamp)};
export const SRI_LANKA_LOCATIONS = ${JSON.stringify(locations, null, 2)};
export const SRI_LANKA_DISTRICTS = Object.keys(SRI_LANKA_LOCATIONS);
`;
await writeFile(new URL("../public/sri-lanka-locations.js", import.meta.url), source, "utf8");
console.log(`Saved ${districts.size} districts and ${Object.values(locations).reduce((sum, names) => sum + names.length, 0)} location options.`);
